#!/usr/bin/env python3
"""Static integration QA for every redone Diezell page in the isolated preview."""
from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import urlsplit,unquote
import json,re

root=Path('site/nuevo').resolve()
pages=sorted(root.rglob('*.html'))
assert len(pages)==37,f'Expected all 37 pages, found {len(pages)}'
class Scan(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.ids=[];self.refs=[];self.h1=0;self.titles=0
    def handle_starttag(self,tag,attrs):
        a=dict(attrs)
        if 'id' in a:self.ids.append(a['id'])
        if tag=='h1':self.h1+=1
        if tag=='title':self.titles+=1
        field={'a':'href','img':'src','script':'src','link':'href','iframe':'src'}.get(tag)
        if field and a.get(field):self.refs.append((tag,a[field]))
scans={}
for page in pages:
    source=page.read_text(encoding='utf-8')
    sc=Scan();sc.feed(source);scans[page]=sc
    assert sc.h1==1,(page,'Expected exactly one H1',sc.h1)
    assert sc.titles==1,(page,'Expected a unique page title')
    assert len(sc.ids)==len(set(sc.ids)),(page,'Duplicate DOM ids')
    assert 'class="stripes"' not in source,(page,'Old decorative stripes remain')
    if page!=root/'index.html':
        assert 'class="dz3 ' in source,(page,'Missing new independent layout')
links_checked=0
for page,sc in scans.items():
    for tag,href in sc.refs:
        if href.startswith(('#','data:','mailto:','tel:','javascript:')) and not href.startswith('#'):continue
        parsed=urlsplit(href)
        if parsed.scheme or parsed.netloc or href.startswith('//'):continue
        if href.startswith('#'):
            target=page
        else:
            path=unquote(parsed.path)
            if not path:continue
            target=(page.parent/path).resolve()
            assert target.is_relative_to(root),(page,href,'Escapes site root')
            assert target.is_file(),(page,href,'Missing local resource')
            links_checked+=1
        anchor=parsed.fragment
        if not anchor:continue
        if target.suffix.lower()=='.html':
            available=scans.get(target)
            if available is None:continue
            if anchor in ('lista-insania','lista-caotico','lista-sencillos'):
                # Generated by the music catalog after playlist load.
                continue
            assert anchor in available.ids,(page,href,'Missing target id')
script=(root/'dz3-links.js').read_text(encoding='utf-8')
m=re.match(r'window\.DZ3_LINKS=(\[.*\]);?\s*$',script,re.S)
assert m,'Song link map malformed'
songs=json.loads(m.group(1))
assert len(songs)==27 and len(set(songs))==27
assert all((root/path).is_file() for path in songs)
for member in ('rene','bernie','emmash','mau'):
    assert 'miembro-'+member+'.html' in (root/'banda.html').read_text(encoding='utf-8')
print(f'PASS: {len(pages)} rebuilt pages, {links_checked} local resource references, 27 song links and 4 member profiles')
